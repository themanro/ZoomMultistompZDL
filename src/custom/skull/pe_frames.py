#!/usr/bin/env python3
"""Put the pedal Skull's own face into the Patch Editor's picture.

Renders the jaw frames exactly as build.py does (skull3d.py's model, same
camera, lit and Bayer-dithered to 1 bit, 128 x 64) and writes them, with the
eye positions, between the SKULL_FRAMES markers in tools/fx_visuals.js.
Run it after changing the model or the camera:

    python3 src/custom/skull/pe_frames.py
"""
import base64
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent.parent
sys.path[:0] = [str(HERE)]
import skull3d as S  # noqa: E402

CAM = dict(scale=0.0178, cy=31)        # build.py's camera
JAW_STEPS, JAW_MAX = 6, 0.34           # build.py's jaw openings


def bits(jaw):
    img, _ = S.render(h=64, jaw=jaw, **CAM)
    bone = S.dither(S.tone(img), "bayer")
    out = bytearray(1024)
    for y in range(64):
        for x in range(128):
            if bone[y, x]:
                out[y * 16 + (x >> 3)] |= 0x80 >> (x & 7)
    return base64.b64encode(bytes(out)).decode()


def main():
    frames = [bits(JAW_MAX * k / (JAW_STEPS - 1)) for k in range(JAW_STEPS)]
    (lx, ly), (rx, ry) = [S.project((sx * 0.17, -0.03, 0.34), **CAM) for sx in (-1, 1)]
    block = ("  /* SKULL_FRAMES:BEGIN generated by src/custom/skull/pe_frames.py: the pedal's own skull,\n"
             "     128 x 64, 1 bit, rows of 16 bytes; jaw shut to open, and the eyes */\n"
             f"  const SKULL_EYES = [[{lx}, {ly}], [{rx}, {ry}]];\n"
             "  const SKULL_JAW = [\n" + "".join(f'    "{f}",\n' for f in frames) + "  ];\n"
             "  /* SKULL_FRAMES:END */")
    path = ROOT / "tools" / "fx_visuals.js"
    js = path.read_text()
    new, n = re.subn(r"  /\* SKULL_FRAMES:BEGIN.*?SKULL_FRAMES:END \*/", lambda m: block, js, flags=re.S)
    if n != 1:
        raise SystemExit("tools/fx_visuals.js: no SKULL_FRAMES markers")
    path.write_text(new)
    print(f"[skull] {len(frames)} jaw frames, eyes {(lx, ly)} {(rx, ry)} -> {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
