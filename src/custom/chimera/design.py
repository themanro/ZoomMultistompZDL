#!/usr/bin/env python3
"""Fit This effect's vowel shapes: one area function per vowel, as a tube of
NSEC sections from the glottis (0) to the lips (NSEC-1).

The acoustics are the ones the Chimera synth uses (github.com/jamesondh/chimera-vocal-synth,
MIT; copyright (c) 2026 Jameson Hodge): a transmission line of cylindrical sections, cgs units, a Flanagan
radiation load at the lips. The synth builds its areas from a 2D head
(tongue, jaw, lips); that geometry is too big for the pedal, so here each
vowel's log-area is a smooth curve (a few cosines, after Mermelstein 1967)
fitted so the tube's first three resonances land on measured formants of
an adult male voice (Peterson & Barney 1952, 17.5 cm tract). The pedal
morphs between these shapes and scales the tube's length (Body).

    python3 src/custom/chimera/design.py          prints the fit, writes chimera_vowels.h
"""
from pathlib import Path
import numpy as np
from scipy.optimize import minimize

HERE = Path(__file__).resolve().parent
NSEC = 16
RHO, C = 1.14e-3, 35000.0              # g/cm^3, cm/s
LEN = 17.5                             # cm, the adult male the targets are for

# Vowel order on the Vowel knob: a back-to-front arc, u o a e i.
VOWELS = [  # name, F1 F2 F3 (Hz), lip area hint (cm^2)
    ("u", (300, 870, 2240), 0.5),
    ("o", (570, 840, 2410), 1.5),
    ("a", (730, 1090, 2440), 5.0),
    ("e", (530, 1840, 2480), 3.0),
    ("i", (270, 2290, 3010), 2.0),
]
NCOS = 5


def areas_of(p):
    """log A(x) = c0 + sum c_k cos(k pi x) at the section centres; the last
    parameter is the lip section's own log-area."""
    x = (np.arange(NSEC) + 0.5) / NSEC
    la = p[0] + sum(p[k] * np.cos(k * np.pi * x) for k in range(1, NCOS + 1))
    la[-1] = p[NCOS + 1]
    la[0] = min(la[0], np.log(1.6))      # the larynx tube stays narrow
    return np.exp(np.clip(la, np.log(0.15), np.log(12.0)))


def response(A, length=LEN, f=None):
    """|U_lips / U_glottis| over f, lossy chain matrices + radiation load."""
    if f is None:
        f = np.arange(50.0, 5000.0, 5.0)
    w = 2 * np.pi * f
    d = length / len(A)
    k = w / C * (1 - 0.0045j)            # a little loss, so peaks are finite
    Mtot = np.zeros((len(f), 2, 2), complex); Mtot[:, 0, 0] = Mtot[:, 1, 1] = 1
    for a in A:
        z = RHO * C / a
        cs, sn = np.cos(k * d), np.sin(k * d)
        M = np.empty_like(Mtot)
        M[:, 0, 0] = cs; M[:, 0, 1] = 1j * z * sn; M[:, 1, 0] = 1j * sn / z; M[:, 1, 1] = cs
        Mtot = Mtot @ M
    al = A[-1]
    R = 128 * RHO * C / (9 * np.pi ** 2 * al)
    L = 8 * RHO / (3 * np.pi * np.sqrt(np.pi * al))
    Zr = (1j * w * L * R) / (R + 1j * w * L)
    H = 1 / (Mtot[:, 1, 0] * Zr + Mtot[:, 1, 1])
    return f, np.abs(H)


def formants(A, length=LEN, n=3):
    f, h = response(A, length)
    pk = [i for i in range(1, len(h) - 1) if h[i] > h[i - 1] and h[i] >= h[i + 1]]
    return [f[i] for i in pk[:n]] + [9999.0] * (n - len(pk[:n]))


def fit(target, lip):
    def cost(p):
        F = formants(areas_of(p))
        e = sum((np.log(F[i] / target[i])) ** 2 for i in range(3))
        e += 0.002 * sum(p[k] ** 2 for k in range(2, NCOS + 1))      # smooth shapes
        e += 0.02 * (p[NCOS + 1] - np.log(lip)) ** 2                  # plausible lips
        return e
    best = None
    rng = np.random.default_rng(1)
    for trial in range(40):
        p0 = np.concatenate([[np.log(3.0)], rng.normal(0, 0.6, NCOS), [np.log(lip)]])
        r = minimize(cost, p0, method="Nelder-Mead", options={"maxiter": 4000, "xatol": 1e-4, "fatol": 1e-7})
        if best is None or r.fun < best.fun:
            best = r
    return areas_of(best.x), best.fun


def main():
    rows = []
    for name, target, lip in VOWELS:
        A, err = fit(target, lip)
        F = formants(A)
        rows.append((name, A))
        print(f"/{name}/ target {target}  got {[int(round(x)) for x in F]}  err {err:.4f}")
        print("     areas", " ".join(f"{a:.2f}" for a in A))
    neutral = np.full(NSEC, 3.0)
    print("neutral tube formants", [int(round(x)) for x in formants(neutral)])
    out = ["/* Generated by design.py: Chimera's vowel area functions, cm^2, glottis -> lips.",
           f" * {NSEC} sections; fitted at a {LEN} cm tract (Body scales the length). */",
           f"#define TH_NSEC {NSEC}", f"#define TH_NVOW {len(rows)}",
           f"static const float TH_VOWEL_LNA[{len(rows)}][{NSEC}] = {{  /* log area */"]
    for name, A in rows:
        out.append("    { " + ", ".join(f"{np.log(a):.5f}f" for a in A) + " },  /* " + name + " */")
    out.append("};")
    (HERE / "chimera_vowels.h").write_text("\n".join(out) + "\n")
    print("wrote chimera_vowels.h")


if __name__ == "__main__":
    main()
